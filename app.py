# ============================================================
# لوحة تحكم مبيعات المطعم - باستخدام Streamlit
# الداتاسيت: tips (من مكتبة seaborn)
# ============================================================

import streamlit as st
import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt
import plotly.express as px

# ------------------------------------------------------------
# إعدادات الصفحة (لازم تكون أول أمر من Streamlit)
# ------------------------------------------------------------
st.set_page_config(page_title="لوحة تحكم مبيعات المطعم", layout="wide")

# ------------------------------------------------------------
# الجزء 1: العنوان وتحميل البيانات
# ------------------------------------------------------------
st.title("لوحة تحكم مبيعات المطعم")
st.write("مرحبًا! هاي أول لوحة تحكم بأبنيها.")

# تحميل بيانات الإكراميات
بيانات_الإكراميات = sns.load_dataset('tips')

# قاموس لتحويل أسماء الأيام من الإنجليزي للعربي (للعرض فقط)
أيام_بالعربي = {
    'Thur': 'الخميس',
    'Fri': 'الجمعة',
    'Sat': 'السبت',
    'Sun': 'الأحد',
}

# قائمة الأيام الموجودة في البيانات
قائمة_الأيام = ['Thur', 'Fri', 'Sat', 'Sun']

# القيم الافتراضية للفلاتر
أقل_فاتورة_افتراضية = 0.0
أعلى_فاتورة_افتراضية = 51.0


# ------------------------------------------------------------
# دالة زر "إعادة تعيين الفلاتر"
# بترجّع الفلاتر لقيمها الأولى
# ------------------------------------------------------------
def إعادة_تعيين_الفلاتر():
    st.session_state['اليوم_المختار'] = قائمة_الأيام[0]
    st.session_state['نطاق_الفاتورة'] = (أقل_فاتورة_افتراضية, أعلى_فاتورة_افتراضية)


# ------------------------------------------------------------
# الجزء 2: الشريط الجانبي (الفلاتر)
# ------------------------------------------------------------
st.sidebar.header("الفلاتر")

# قائمة اختيار اليوم
اليوم_المختار = st.sidebar.selectbox(
    "اختر اليوم",
    options=قائمة_الأيام,
    format_func=lambda يوم: أيام_بالعربي[يوم],  # نعرض اسم اليوم بالعربي
    key='اليوم_المختار',
)

# شريط تحديد نطاق الفاتورة
نطاق_الفاتورة = st.sidebar.slider(
    "نطاق قيمة الفاتورة",
    min_value=أقل_فاتورة_افتراضية,
    max_value=أعلى_فاتورة_افتراضية,
    value=(أقل_فاتورة_افتراضية, أعلى_فاتورة_افتراضية),
    step=1.0,
    key='نطاق_الفاتورة',
)
أقل_فاتورة = نطاق_الفاتورة[0]
أعلى_فاتورة = نطاق_الفاتورة[1]

# زر إعادة التعيين (لما نضغطه بينفذ الدالة اللي فوق)
st.sidebar.button("إعادة تعيين الفلاتر", on_click=إعادة_تعيين_الفلاتر)

# ------------------------------------------------------------
# الجزء 4: فلترة البيانات حسب اختيارات المستخدم
# ------------------------------------------------------------
الإكراميات_المفلترة = بيانات_الإكراميات[
    (بيانات_الإكراميات['day'] == اليوم_المختار) &
    (بيانات_الإكراميات['total_bill'] >= أقل_فاتورة) &
    (بيانات_الإكراميات['total_bill'] <= أعلى_فاتورة)
]

# ------------------------------------------------------------
# المؤشرات (KPIs) - تحت العنوان مباشرة
# ------------------------------------------------------------
# إذا ما في بيانات نخلي القيم صفر عشان ما يطلع خطأ
if len(الإكراميات_المفلترة) > 0:
    عدد_الطلبات = len(الإكراميات_المفلترة)
    متوسط_الفاتورة = الإكراميات_المفلترة['total_bill'].mean()
    متوسط_الإكرامية = الإكراميات_المفلترة['tip'].mean()
else:
    عدد_الطلبات = 0
    متوسط_الفاتورة = 0
    متوسط_الإكرامية = 0

# 3 أعمدة جنب بعض
العمود_الأول, العمود_الثاني, العمود_الثالث = st.columns(3)
العمود_الأول.metric("عدد الطلبات", عدد_الطلبات)
العمود_الثاني.metric("متوسط الفاتورة", f"${متوسط_الفاتورة:.2f}")
العمود_الثالث.metric("متوسط الإكرامية", f"${متوسط_الإكرامية:.2f}")

# ------------------------------------------------------------
# رسالة تحذيرية إذا الفلتر رجّع بيانات فاضية
# ------------------------------------------------------------
if الإكراميات_المفلترة.empty:
    st.warning("لا توجد طلبات تطابق الفلاتر المختارة، جرّب تغيير اليوم أو توسيع نطاق الفاتورة.")
    st.stop()  # نوقف الصفحة هون لأنو ما في بيانات نرسمها

# ------------------------------------------------------------
# الجزء 3: الرسومات داخل تبويبات
# ------------------------------------------------------------
تبويب_النظرة_العامة, تبويب_التفاصيل = st.tabs(["نظرة عامة", "تفاصيل"])

with تبويب_النظرة_العامة:
    عمود_الهيستوغرام, عمود_الأعمدة = st.columns(2)

    # --- رسم 1: Histogram لتوزيع الفاتورة (Matplotlib / Seaborn) ---
    with عمود_الهيستوغرام:
        st.subheader("توزيع قيمة الفاتورة")
        الشكل, المحور = plt.subplots()
        sns.histplot(الإكراميات_المفلترة['total_bill'], bins=10, kde=True, ax=المحور)
        # ملاحظة: نكتب عناوين الرسم بالإنجليزي لأنو Matplotlib ما بيعرض العربي صح
        المحور.set_xlabel("Total Bill")
        المحور.set_ylabel("Count")
        st.pyplot(الشكل)

    # --- رسم 2: Bar Chart تفاعلي (Plotly) لمتوسط الإكرامية حسب اليوم ---
    with عمود_الأعمدة:
        st.subheader("متوسط الإكرامية حسب اليوم")
        بيانات_الأعمدة = (
            الإكراميات_المفلترة
            .groupby('day', observed=True)['tip']
            .mean()
            .reset_index()
        )
        # نضيف عمود فيه اسم اليوم بالعربي
        بيانات_الأعمدة['اليوم'] = بيانات_الأعمدة['day'].map(أيام_بالعربي)
        شكل_الأعمدة = px.bar(
            بيانات_الأعمدة,
            x='اليوم',
            y='tip',
            labels={'tip': 'متوسط الإكرامية'},
        )
        st.plotly_chart(شكل_الأعمدة)

with تبويب_التفاصيل:
    st.subheader("جدول الطلبات المفلترة")
    st.dataframe(الإكراميات_المفلترة)